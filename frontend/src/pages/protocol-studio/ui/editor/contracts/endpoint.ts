import { parseDocument, stringify } from "yaml";

import type { ContractFileId } from "@pages/protocol-studio/ui/editor/contracts/github";

/** The slice of `useGetSpecQuery`'s answer the fallback reads. */
export interface SpecServiceDoc {
    paths?: unknown;
    components?: unknown;
    "x-supported-actions"?: unknown;
    "x-validations"?: unknown;
    info?: { "x-branch-name"?: string };
}

const HEADER = (what: string) =>
    `# Generated by Studio from the spec service's ${what}: read-only.\n` +
    "# Comments and shared anchors aren't in it. Import the files from GitHub to edit.\n";

/**
 * The spec service's copy of a contract file as YAML, for viewing until the
 * real file is imported. Aliases were resolved by the service and comments
 * dropped, so this can only be looked at, never round-tripped.
 */
export const endpointText = (
    doc: SpecServiceDoc | undefined,
    id: ContractFileId
): string | undefined => {
    if (!doc) return undefined;
    const dump = (value: unknown, what: string) =>
        HEADER(what) + stringify(value, { aliasDuplicateObjects: false, lineWidth: 0 });
    if (id === "actions") {
        const actions = doc["x-supported-actions"];
        return actions && typeof actions === "object"
            ? dump(actions, "x-supported-actions")
            : undefined;
    }
    if (id === "validations") {
        const validations = doc["x-validations"];
        return validations && typeof validations === "object"
            ? dump(validations, "x-validations")
            : undefined;
    }
    if (!doc.paths) return undefined;
    return dump({ paths: doc.paths, components: doc.components ?? {} }, "paths and components");
};

/** Which contract a file is, from its top-level keys (for uploads). */
export const detectContractKind = (text: string): ContractFileId | null => {
    let root: unknown;
    try {
        root = parseDocument(text, { logLevel: "silent" }).toJS({ maxAliasCount: -1 });
    } catch {
        return null;
    }
    if (!root || typeof root !== "object") return null;
    const keys = Object.keys(root);
    if (keys.includes("_TESTS_")) return "validations";
    if (keys.includes("supportedActions") || keys.includes("apiProperties")) return "actions";
    if (keys.includes("paths") || keys.includes("openapi") || keys.includes("components"))
        return "specs";
    return null;
};
